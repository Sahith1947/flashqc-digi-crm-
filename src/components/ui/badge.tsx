import type { ReactNode } from 'react';
import { ArrowDownLeft, ArrowUpRight, CheckCircle2, CircleDashed, FlaskConical, OctagonAlert, TriangleAlert, Info } from 'lucide-react';
import { cn } from '@/lib/cn';
import { CALL_STATUS_LABELS, CALL_STATUS_TONE, labelFor, type Tone } from '@/lib/constants';

const toneClass: Record<Tone, string> = {
  good: 'bg-green-50 text-green-800 ring-green-600/20',
  warning: 'bg-amber-50 text-amber-800 ring-amber-600/25',
  serious: 'bg-orange-50 text-orange-800 ring-orange-600/25',
  critical: 'bg-red-50 text-red-800 ring-red-600/20',
  neutral: 'bg-neutral-100 text-neutral-700 ring-neutral-500/20',
  info: 'bg-blue-50 text-blue-800 ring-blue-600/20',
  brand: 'bg-brand-50 text-brand-800 ring-brand-600/25',
};
const toneIcon: Record<Tone, ReactNode> = {
  good: <CheckCircle2 className="size-3.5" aria-hidden />,
  warning: <TriangleAlert className="size-3.5" aria-hidden />,
  serious: <TriangleAlert className="size-3.5" aria-hidden />,
  critical: <OctagonAlert className="size-3.5" aria-hidden />,
  neutral: <CircleDashed className="size-3.5" aria-hidden />,
  info: <Info className="size-3.5" aria-hidden />,
  brand: null,
};

export function Badge({ tone = 'neutral', icon = true, children, className, title }: { tone?: Tone; icon?: boolean; children: ReactNode; className?: string; title?: string }) {
  return (
    <span
      title={title}
      className={cn('inline-flex items-center gap-1 rounded-md px-2 py-0.5 text-xs font-medium whitespace-nowrap ring-1 ring-inset', toneClass[tone], className)}
    >
      {icon && toneIcon[tone]}
      {children}
    </span>
  );
}

export function CallStatusBadge({ status }: { status: string }) {
  const tone = (CALL_STATUS_TONE as Record<string, Tone>)[status] ?? 'neutral';
  return <Badge tone={tone}>{labelFor(CALL_STATUS_LABELS, status)}</Badge>;
}

export function SimulatedBadge({ className }: { className?: string }) {
  return (
    <span
      title="Generated by the simulator. Not a real call."
      className={cn('inline-flex items-center gap-1 rounded-md bg-violet-50 px-1.5 py-0.5 text-[11px] font-semibold tracking-wide text-violet-800 uppercase ring-1 ring-violet-600/20 ring-inset', className)}
    >
      <FlaskConical className="size-3" aria-hidden />
      Simulated
    </span>
  );
}

export function DirectionBadge({ direction }: { direction: string }) {
  const inbound = direction === 'inbound';
  return (
    <span className="inline-flex items-center gap-1 text-xs font-medium text-ink-2">
      <span className={cn('inline-flex size-5 items-center justify-center rounded-full', inbound ? 'bg-blue-50 text-blue-700' : 'bg-brand-50 text-brand-700')}>
        {inbound ? <ArrowDownLeft className="size-3.5" aria-hidden /> : <ArrowUpRight className="size-3.5" aria-hidden />}
      </span>
      {inbound ? 'Inbound' : 'Outbound'}
    </span>
  );
}
