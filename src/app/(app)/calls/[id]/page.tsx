import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { ArrowLeft, Sparkles, Trash2 } from 'lucide-react';
import { requireMember } from '@/server/auth';
import { CallEventService } from '@/server/services/call-event-service';
import { RecordingService } from '@/server/services/recording-service';
import { TranscriptService } from '@/server/services/transcript-service';
import { isUuid } from '@/lib/list-params';
import { formatDateTime, formatDuration } from '@/lib/dates';
import { formatPhone } from '@/lib/phone';
import { hasMinRole } from '@/lib/constants';
import { PageHeader } from '@/components/ui/page-header';
import { Card, CardBody, CardHeader } from '@/components/ui/card';
import { CallStatusBadge, DirectionBadge, SimulatedBadge, Badge } from '@/components/ui/badge';
import { Notice } from '@/components/ui/states';
import { Button } from '@/components/ui/button';
import { ConfirmAction } from '@/components/ui/confirm-action';
import { callRef } from '@/components/calls/calls-table';
import { OutcomeForm, RecordingUploader, SaveContactForm } from '@/components/calls/call-detail-forms';
import { EditableSection } from '@/components/calls/editable-section';
import { deleteCall, deleteRecording, deleteSummary, deleteTranscript } from '../actions';

export const metadata: Metadata = { title: 'Call details' };

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="flex justify-between gap-4 border-b border-line py-2 text-sm last:border-0">
      <dt className="text-ink-3">{label}</dt>
      <dd className="text-right text-ink">{children}</dd>
    </div>
  );
}

export default async function CallDetailPage(props: PageProps<'/calls/[id]'>) {
  const { id } = await props.params;
  if (!isUuid(id)) notFound();
  const { db, profile } = await requireMember();
  const { data: call, error } = await db.from('call_log_view').select('*').eq('id', id).maybeSingle();
  if (error) throw error;
  if (!call) notFound();

  const [events, recordingsRes, transcriptRes, summaryRes] = await Promise.all([
    CallEventService.list(db, id),
    db.from('call_recordings').select('*').eq('call_id', id).order('created_at', { ascending: false }),
    db.from('call_transcripts').select('*').eq('call_id', id).maybeSingle(),
    db.from('call_summaries').select('*').eq('call_id', id).maybeSingle(),
  ]);
  const recordings = await Promise.all(
    (recordingsRes.data ?? []).map(async (r) => ({ ...r, playback: await RecordingService.getPlaybackUrl(db, r) })),
  );
  const transcript = transcriptRes.data;
  const summary = summaryRes.data;
  const ai = TranscriptService.isAiAvailable();
  const canAgent = hasMinRole(profile.role, 'agent');
  const canManager = hasMinRole(profile.role, 'manager');
  const canAdmin = hasMinRole(profile.role, 'admin');

  return (
    <>
      <Link href="/calls" className="mb-3 inline-flex items-center gap-1 text-sm text-ink-2 hover:text-ink">
        <ArrowLeft className="size-4" /> Call Logs
      </Link>
      <PageHeader
        title={`${callRef(call.call_number)} · ${call.contact_name || formatPhone(call.phone_e164)}`}
        description={
          <span className="flex flex-wrap items-center gap-2">
            <DirectionBadge direction={call.direction ?? ''} />
            <CallStatusBadge status={call.status ?? ''} />
            {call.is_simulated && <SimulatedBadge />}
            <span className="text-ink-3">{formatDateTime(call.started_at)} IST</span>
          </span>
        }
        actions={
          canAdmin ? (
            <ConfirmAction
              action={deleteCall.bind(null, id)}
              label="Delete call"
              icon={<Trash2 className="size-4" />}
              title="Delete this call?"
              description="The call, its events, recordings, transcript and summary will be permanently deleted. This cannot be undone."
              confirmLabel="Delete permanently"
              testId="delete-call"
            />
          ) : undefined
        }
      />
      {call.is_simulated && (
        <Notice tone="sim" className="mb-6">
          This call was generated by the simulator for testing. No real phone call took place, and it has no real recording.
        </Notice>
      )}

      <div className="grid gap-6 xl:grid-cols-3">
        <div className="space-y-6 xl:col-span-2">
          <Card>
            <CardHeader title="Recording" description="Private storage · signed playback links expire after 1 hour" />
            <CardBody className="space-y-4">
              {recordings.length === 0 && <p className="text-sm text-ink-3">No recording for this call.</p>}
              {recordings.map((r) => (
                <div key={r.id} className="rounded-lg border border-line p-3">
                  <div className="mb-2 flex flex-wrap items-center justify-between gap-2 text-xs text-ink-3">
                    <span>
                      {r.source === 'upload' ? 'Uploaded' : 'From provider'} · {formatDateTime(r.created_at)}
                      {r.duration_seconds != null && ` · ${formatDuration(r.duration_seconds)}`}
                      {r.size_bytes != null && ` · ${r.size_bytes < 1048576 ? `${Math.max(1, Math.round(r.size_bytes / 1024))} KB` : `${(r.size_bytes / 1048576).toFixed(1)} MB`}`}
                    </span>
                    {canManager && (
                      <ConfirmAction
                        action={deleteRecording.bind(null, r.id, id)}
                        label="Delete"
                        icon={<Trash2 className="size-3.5" />}
                        title="Delete recording?"
                        description="The audio file will be permanently removed from storage."
                        confirmLabel="Delete"
                      />
                    )}
                  </div>
                  {r.playback.url ? (
                    <audio controls preload="none" src={r.playback.url} className="w-full" data-testid="recording-player">
                      Your browser does not support audio playback.
                    </audio>
                  ) : (
                    <Notice tone="warning">{r.playback.error}</Notice>
                  )}
                </div>
              ))}
              {canAgent && !call.is_simulated && <RecordingUploader callId={id} />}
              {canAgent && call.is_simulated && <p className="text-xs text-ink-3">Recordings cannot be attached to simulated calls.</p>}
            </CardBody>
          </Card>

          <Card>
            <CardHeader
              title="AI summary"
              action={
                <Button variant="secondary" size="sm" icon={<Sparkles className="size-3.5" />} disabled title="Available after the Sarvam AI integration (Phase 2)">
                  {ai.summaries ? 'Generate' : 'Generate (Phase 2)'}
                </Button>
              }
              description={summary ? `${summary.source === 'ai' ? `AI · ${summary.model ?? ''}` : 'Written manually'} · updated ${formatDateTime(summary.updated_at)}` : 'AI summaries will be generated automatically once Sarvam AI is connected.'}
            />
            <CardBody>
              <EditableSection
                canEdit={canAgent && (!summary || summary.source === 'manual')}
                hasContent={Boolean(summary)}
                emptyLabel="No summary yet."
                view={
                  <div className="space-y-2" data-testid="summary-view">
                    {summary?.sentiment && <Badge tone={summary.sentiment === 'positive' ? 'good' : summary.sentiment === 'negative' ? 'critical' : 'neutral'}>{summary.sentiment}</Badge>}
                    <p className="text-sm whitespace-pre-wrap text-ink">{summary?.summary}</p>
                  </div>
                }
                editor={{ type: 'summary', callId: id, summary: summary?.summary ?? '', sentiment: summary?.sentiment ?? null }}
              />
              {summary && canManager && (
                <div className="mt-3">
                  <ConfirmAction action={deleteSummary.bind(null, id)} label="Delete summary" title="Delete summary?" description="This summary will be removed." confirmLabel="Delete" />
                </div>
              )}
            </CardBody>
          </Card>

          <Card>
            <CardHeader
              title="Transcript"
              description={transcript ? `${transcript.source === 'manual' ? 'Entered manually' : `From ${transcript.provider ?? transcript.source}`}${transcript.language ? ` · ${transcript.language}` : ''}` : 'Transcripts will be produced by Sarvam AI speech-to-text in Phase 2.'}
            />
            <CardBody>
              <EditableSection
                canEdit={canAgent && (!transcript || transcript.source === 'manual')}
                hasContent={Boolean(transcript)}
                emptyLabel="No transcript yet."
                view={<pre className="max-h-96 overflow-auto rounded-lg bg-canvas p-3 font-sans text-sm whitespace-pre-wrap text-ink" data-testid="transcript-view">{transcript?.content}</pre>}
                editor={{ type: 'transcript', callId: id, content: transcript?.content ?? '', language: transcript?.language ?? null }}
              />
              {transcript && canManager && (
                <div className="mt-3">
                  <ConfirmAction action={deleteTranscript.bind(null, id)} label="Delete transcript" title="Delete transcript?" description="This transcript will be removed." confirmLabel="Delete" />
                </div>
              )}
            </CardBody>
          </Card>

          <Card>
            <CardHeader title="Event timeline" description={`${events.length} event${events.length === 1 ? '' : 's'} · IST`} />
            <CardBody>
              {events.length === 0 ? (
                <p className="text-sm text-ink-3">No events recorded.</p>
              ) : (
                <ol className="relative space-y-4 border-l border-line pl-5" data-testid="event-timeline">
                  {events.map((e) => (
                    <li key={e.id} className="relative">
                      <span className="absolute top-1.5 -left-[25px] size-2.5 rounded-full border-2 border-surface bg-brand-500" aria-hidden />
                      <p className="text-sm font-medium text-ink">{e.event_type.replace(/_/g, ' ')}</p>
                      <p className="text-xs text-ink-3">
                        {formatDateTime(e.occurred_at)} · source: {e.source}
                        {e.status && ` · status: ${e.status}`}
                      </p>
                    </li>
                  ))}
                </ol>
              )}
            </CardBody>
          </Card>
        </div>

        <div className="space-y-6">
          <Card>
            <CardHeader title="Outcome & notes" />
            <CardBody>
              <OutcomeForm callId={id} outcome={call.outcome} notes={call.notes} canEdit={canAgent} />
            </CardBody>
          </Card>
          <Card>
            <CardHeader title="Contact" />
            <CardBody>
              {call.contact_id ? (
                <dl>
                  <Row label="Name">
                    <Link href={`/contacts/${call.contact_id}`} className="font-medium text-brand-700 hover:underline">
                      {call.contact_name || 'Unnamed contact'}
                    </Link>
                  </Row>
                  <Row label="Phone">{formatPhone(call.phone_e164)}</Row>
                  <Row label="Business">{call.business_name || '—'}</Row>
                </dl>
              ) : (
                <div className="space-y-3">
                  <p className="text-sm text-ink-2">
                    {formatPhone(call.phone_e164)} is not saved as a contact.
                  </p>
                  {canAgent && <SaveContactForm callId={id} />}
                </div>
              )}
            </CardBody>
          </Card>
          <Card>
            <CardHeader title="Call details" />
            <CardBody>
              <dl>
                <Row label="Started">{formatDateTime(call.started_at)}</Row>
                <Row label="Answered">{formatDateTime(call.answered_at)}</Row>
                <Row label="Ended">{formatDateTime(call.ended_at)}</Row>
                <Row label="Talk time">{call.is_answered ? formatDuration(call.duration_seconds) : '—'}</Row>
                <Row label="Business line">{call.phone_number_label ? `${call.phone_number_label} (${formatPhone(call.business_phone_e164)})` : '—'}</Row>
                <Row label="Voice agent">{call.voice_agent_name || '—'}</Row>
                <Row label="Campaign">
                  {call.campaign_id ? (
                    <Link href={`/campaigns/${call.campaign_id}`} className="text-brand-700 hover:underline">
                      {call.campaign_name}
                    </Link>
                  ) : (
                    '—'
                  )}
                </Row>
                <Row label="Provider">{call.is_simulated ? 'Simulator' : call.provider || '—'}</Row>
                {call.provider_call_id && <Row label="Provider call ID">{call.provider_call_id}</Row>}
                {call.failure_reason && <Row label="Failure reason">{call.failure_reason}</Row>}
              </dl>
            </CardBody>
          </Card>
        </div>
      </div>
    </>
  );
}
